-- ONS Postcode Directory, February 2024 release: one row per UK postcode,
-- live or terminated, with the areas it fell in then. It is the last release
-- before the 2024 constituency boundaries, kept for its older areas: pcon
-- holds the constituencies of the 2010-2019 general elections. Only that one
-- file's rows are kept; the current release is stg_onspd. Its columns have
-- the names ONSPD used before 2025 (pcon, oslaua, osward...).
with raw as (
    -- duckpipe keeps each CSV row in record, every value as text.
    select
        record->>'pcd' as pcd,
        record->>'pcd2' as pcd2,
        record->>'pcds' as pcds,
        record->>'dointr' as dointr,
        record->>'doterm' as doterm,
        record->>'usertype' as usertype,
        record->>'oseast1m' as oseast1m,
        record->>'osnrth1m' as osnrth1m,
        record->>'osgrdind' as osgrdind,
        record->>'lat' as lat,
        record->>'long' as long,
        record->>'ctry' as ctry,
        record->>'rgn' as rgn,
        record->>'oscty' as oscty,
        record->>'ced' as ced,
        record->>'oslaua' as oslaua,
        record->>'osward' as osward,
        record->>'parish' as parish,
        record->>'pcon' as pcon,
        record->>'eer' as eer,
        record->>'teclec' as teclec,
        record->>'itl' as itl,
        record->>'ttwa' as ttwa,
        record->>'bua11' as bua11,
        record->>'buasd11' as buasd11,
        record->>'npark' as npark,
        record->>'pfa' as pfa,
        record->>'calncv' as calncv,
        record->>'lep1' as lep1,
        record->>'lep2' as lep2,
        record->>'oshlthau' as oshlthau,
        record->>'nhser' as nhser,
        record->>'icb' as icb,
        record->>'sicbl' as sicbl,
        record->>'pct' as pct,
        record->>'oa21' as oa21,
        record->>'lsoa21' as lsoa21,
        record->>'msoa21' as msoa21,
        record->>'oa11' as oa11,
        record->>'lsoa11' as lsoa11,
        record->>'msoa11' as msoa11,
        record->>'wz11' as wz11,
        record->>'ru11ind' as ru11ind,
        record->>'oac11' as oac11,
        record->>'oa01' as oa01,
        record->>'lsoa01' as lsoa01,
        record->>'msoa01' as msoa01,
        record->>'ur01ind' as ur01ind,
        record->>'oac01' as oac01,
        record->>'statsward' as statsward,
        record->>'casward' as casward,
        record->>'streg' as streg,
        record->>'imd' as imd,
        _file,
        _loaded_at
    from {{ source('uk', 'onspd') }}
    where _file like '%/ONSPD_FEB_2024_UK.csv'
    -- A file downloaded again replaces its earlier load.
    qualify _loaded_at = max(_loaded_at) over ()
)
select
    pcds,  -- e.g. AB1 0AA, the format price paid uses
    pcd,
    pcd2,
    strptime(dointr, '%Y%m')::date as dointr,
    strptime(doterm, '%Y%m')::date as doterm,  -- null while the postcode is live
    usertype = '1' as is_large_user,
    osgrdind,
    -- Postcodes without a grid reference (osgrdind 9) have 99.999999, 0, no
    -- easting or northing, IMD rank 0, and often no areas at all.
    case when osgrdind <> '9' then oseast1m::integer end as oseast1m,
    case when osgrdind <> '9' then osnrth1m::integer end as osnrth1m,
    case when osgrdind <> '9' then lat::double end as lat,
    case when osgrdind <> '9' then long::double end as long,
    {{ area_code('ctry') }} as ctry,
    {{ area_code('rgn') }} as rgn,
    {{ area_code('oscty') }} as oscty,
    {{ area_code('ced') }} as ced,
    {{ area_code('oslaua') }} as oslaua,
    {{ area_code('osward') }} as osward,
    {{ area_code('parish') }} as parish,
    {{ area_code('pcon') }} as pcon,
    {{ area_code('eer') }} as eer,
    {{ area_code('teclec') }} as teclec,
    {{ area_code('itl') }} as itl,
    {{ area_code('ttwa') }} as ttwa,
    {{ area_code('bua11') }} as bua11,
    {{ area_code('buasd11') }} as buasd11,
    -- E65000001 and W31000001 are England's and Wales's "not in a national park".
    case when npark not in ('E65000001', 'W31000001') then {{ area_code('npark') }} end as npark,
    {{ area_code('pfa') }} as pfa,
    {{ area_code('calncv') }} as calncv,
    {{ area_code('lep1') }} as lep1,
    {{ area_code('lep2') }} as lep2,
    {{ area_code('oshlthau') }} as oshlthau,
    {{ area_code('nhser') }} as nhser,
    {{ area_code('icb') }} as icb,
    {{ area_code('sicbl') }} as sicbl,
    {{ area_code('pct') }} as pct,
    {{ area_code('oa21') }} as oa21,
    {{ area_code('lsoa21') }} as lsoa21,
    {{ area_code('msoa21') }} as msoa21,
    {{ area_code('oa11') }} as oa11,
    {{ area_code('lsoa11') }} as lsoa11,
    {{ area_code('msoa11') }} as msoa11,
    {{ area_code('wz11') }} as wz11,
    ru11ind,
    oac11,
    {{ area_code('oa01') }} as oa01,
    {{ area_code('lsoa01') }} as lsoa01,
    {{ area_code('msoa01') }} as msoa01,
    ur01ind,
    oac01,
    {{ area_code('statsward') }} as statsward,
    {{ area_code('casward') }} as casward,
    streg,
    nullif(imd, '0')::integer as imd,
    _file,
    _loaded_at
from raw
