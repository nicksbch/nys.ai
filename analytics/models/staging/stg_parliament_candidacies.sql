-- UK Parliament election results, one row per candidacy: a candidate standing
-- in one constituency election (election_url) of a general election. The
-- election, constituency and parliament columns repeat on each candidate's
-- row. Each general election is its own file; a file can be downloaded
-- again with corrections, so only the latest load of each file is kept.
with raw as (
    -- duckpipe keeps each CSV row in record, every value as text; empty
    -- fields are missing (null).
    select
        record->>'parliament_number' as parliament_number,
        record->>'parliament_summoned_on' as parliament_summoned_on,
        record->>'parliament_dissolved_on' as parliament_dissolved_on,
        record->>'parliament_wikidata_id' as parliament_wikidata_id,
        record->>'parliament_london_gazette_citation' as parliament_london_gazette_citation,
        record->>'parliament_url' as parliament_url,
        record->>'general_election_polling_date' as general_election_polling_date,
        record->>'general_election_is_notional' as general_election_is_notional,
        record->>'total_electorate_in_general_election' as total_electorate_in_general_election,
        record->>'total_valid_votes_in_general_election' as total_valid_votes_in_general_election,
        record->>'total_invalid_votes_in_general_election' as total_invalid_votes_in_general_election,
        record->>'general_election_url' as general_election_url,
        record->>'country_name' as country_name,
        record->>'country_geographic_code' as country_geographic_code,
        record->>'country_url' as country_url,
        record->>'english_region_name' as english_region_name,
        record->>'english_region_geographic_code' as english_region_geographic_code,
        record->>'english_region_url' as english_region_url,
        record->>'constituency_name' as constituency_name,
        record->>'constituency_geographic_code' as constituency_geographic_code,
        record->>'constituency_designation' as constituency_designation,
        record->>'constituency_url' as constituency_url,
        record->>'boundary_set_start_date' as boundary_set_start_date,
        record->>'boundary_set_end_date' as boundary_set_end_date,
        record->>'boundary_set_url' as boundary_set_url,
        record->>'electorate' as electorate,
        record->>'election_polling_date' as election_polling_date,
        record->>'election_is_byelection' as election_is_byelection,
        record->>'declaration_time' as declaration_time,
        record->>'election_valid_vote_count' as election_valid_vote_count,
        record->>'election_invalid_vote_count' as election_invalid_vote_count,
        record->>'election_url' as election_url,
        record->>'election_result_summary' as election_result_summary,
        record->>'candidate_family_name' as candidate_family_name,
        record->>'candidate_given_name' as candidate_given_name,
        record->>'candidate_mnis_id' as candidate_mnis_id,
        record->>'candidate_is_sitting_mp' as candidate_is_sitting_mp,
        record->>'candidate_is_former_mp' as candidate_is_former_mp,
        record->>'candidate_member_url' as candidate_member_url,
        record->>'main_party_name' as main_party_name,
        record->>'main_party_abbreviation' as main_party_abbreviation,
        record->>'main_party_mnis_id' as main_party_mnis_id,
        record->>'main_party_url' as main_party_url,
        record->>'adjunct_party_name' as adjunct_party_name,
        record->>'adjunct_party_abbreviation' as adjunct_party_abbreviation,
        record->>'candidate_is_standing_as_commons_speaker' as candidate_is_standing_as_commons_speaker,
        record->>'candidate_is_standing_as_independent' as candidate_is_standing_as_independent,
        record->>'candidate_is_notional_political_party_aggregate' as candidate_is_notional_political_party_aggregate,
        record->>'candidate_vote_count' as candidate_vote_count,
        record->>'candidate_vote_share' as candidate_vote_share,
        record->>'candidate_vote_change' as candidate_vote_change,
        record->>'majority' as majority,
        record->>'candidate_result_position' as candidate_result_position,
        _file,
        _loaded_at
    from {{ source('uk', 'parliament_candidacies') }}
    qualify _loaded_at = max(_loaded_at) over (partition by _file)
)
select
    -- The grain key: the source has no candidacy id; a constituency election
    -- and its result position identify one.
    election_url || '#' || candidate_result_position as candidacy_key,
    parliament_number::integer as parliament_number,
    parliament_summoned_on::date as parliament_summoned_on,
    parliament_dissolved_on::date as parliament_dissolved_on,
    parliament_wikidata_id,
    parliament_london_gazette_citation,
    parliament_url,
    general_election_polling_date::date as general_election_polling_date,
    general_election_is_notional::boolean as general_election_is_notional,
    total_electorate_in_general_election::bigint as total_electorate_in_general_election,
    total_valid_votes_in_general_election::bigint as total_valid_votes_in_general_election,
    total_invalid_votes_in_general_election::bigint as total_invalid_votes_in_general_election,
    general_election_url,
    country_name,
    country_geographic_code,
    country_url,
    english_region_name,
    english_region_geographic_code,
    english_region_url,
    constituency_name,
    constituency_geographic_code,
    constituency_designation,
    constituency_url,
    boundary_set_start_date::date as boundary_set_start_date,
    boundary_set_end_date::date as boundary_set_end_date,
    boundary_set_url,
    electorate::integer as electorate,
    election_polling_date::date as election_polling_date,
    election_is_byelection::boolean as election_is_byelection,
    declaration_time::timestamptz as declaration_time,  -- "2010-05-07 03:05:00 UTC"
    election_valid_vote_count::integer as election_valid_vote_count,
    election_invalid_vote_count::integer as election_invalid_vote_count,
    election_url,
    election_result_summary,
    candidate_family_name,
    candidate_given_name,
    candidate_mnis_id::integer as candidate_mnis_id,
    candidate_is_sitting_mp::boolean as candidate_is_sitting_mp,
    candidate_is_former_mp::boolean as candidate_is_former_mp,
    candidate_member_url,
    main_party_name,
    main_party_abbreviation,
    main_party_mnis_id::integer as main_party_mnis_id,
    main_party_url,
    adjunct_party_name,
    adjunct_party_abbreviation,
    candidate_is_standing_as_commons_speaker::boolean as candidate_is_standing_as_commons_speaker,
    candidate_is_standing_as_independent::boolean as candidate_is_standing_as_independent,
    candidate_is_notional_political_party_aggregate::boolean as candidate_is_notional_political_party_aggregate,
    candidate_vote_count::integer as candidate_vote_count,
    candidate_vote_share::double as candidate_vote_share,  -- some in exponent form (5.2e-05)
    candidate_vote_change::double as candidate_vote_change,
    majority::integer as majority,
    candidate_result_position::integer as candidate_result_position,
    _file,
    _loaded_at
from raw
