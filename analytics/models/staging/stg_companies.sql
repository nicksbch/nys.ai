-- Companies House basic company data, one row per live company on the
-- register (dissolved companies are not in the file). Each monthly release
-- is a full snapshot that replaces the last, so only the rows of the latest
-- loaded file are kept.
with raw as (
    -- duckpipe keeps each CSV row in record, every value as text.
    select
        record->>'companyname' as companyname,
        record->>'companynumber' as companynumber,
        record->>'regaddresscareof' as regaddresscareof,
        record->>'regaddresspobox' as regaddresspobox,
        record->>'regaddressaddressline1' as regaddressaddressline1,
        record->>'regaddressaddressline2' as regaddressaddressline2,
        record->>'regaddressposttown' as regaddressposttown,
        record->>'regaddresscounty' as regaddresscounty,
        record->>'regaddresscountry' as regaddresscountry,
        record->>'regaddresspostcode' as regaddresspostcode,
        record->>'companycategory' as companycategory,
        record->>'companystatus' as companystatus,
        record->>'countryoforigin' as countryoforigin,
        record->>'dissolutiondate' as dissolutiondate,
        record->>'incorporationdate' as incorporationdate,
        record->>'accountsaccountrefday' as accountsaccountrefday,
        record->>'accountsaccountrefmonth' as accountsaccountrefmonth,
        record->>'accountsnextduedate' as accountsnextduedate,
        record->>'accountslastmadeupdate' as accountslastmadeupdate,
        record->>'accountsaccountcategory' as accountsaccountcategory,
        record->>'returnsnextduedate' as returnsnextduedate,
        record->>'returnslastmadeupdate' as returnslastmadeupdate,
        record->>'mortgagesnummortcharges' as mortgagesnummortcharges,
        record->>'mortgagesnummortoutstanding' as mortgagesnummortoutstanding,
        record->>'mortgagesnummortpartsatisfied' as mortgagesnummortpartsatisfied,
        record->>'mortgagesnummortsatisfied' as mortgagesnummortsatisfied,
        record->>'siccodesictext_1' as siccodesictext_1,
        record->>'siccodesictext_2' as siccodesictext_2,
        record->>'siccodesictext_3' as siccodesictext_3,
        record->>'siccodesictext_4' as siccodesictext_4,
        record->>'limitedpartnershipsnumgenpartners' as limitedpartnershipsnumgenpartners,
        record->>'limitedpartnershipsnumlimpartners' as limitedpartnershipsnumlimpartners,
        record->>'uri' as uri,
        record->>'previousname_1condate' as previousname_1condate,
        record->>'previousname_1companyname' as previousname_1companyname,
        record->>'previousname_2condate' as previousname_2condate,
        record->>'previousname_2companyname' as previousname_2companyname,
        record->>'previousname_3condate' as previousname_3condate,
        record->>'previousname_3companyname' as previousname_3companyname,
        record->>'previousname_4condate' as previousname_4condate,
        record->>'previousname_4companyname' as previousname_4companyname,
        record->>'previousname_5condate' as previousname_5condate,
        record->>'previousname_5companyname' as previousname_5companyname,
        record->>'previousname_6condate' as previousname_6condate,
        record->>'previousname_6companyname' as previousname_6companyname,
        record->>'previousname_7condate' as previousname_7condate,
        record->>'previousname_7companyname' as previousname_7companyname,
        record->>'previousname_8condate' as previousname_8condate,
        record->>'previousname_8companyname' as previousname_8companyname,
        record->>'previousname_9condate' as previousname_9condate,
        record->>'previousname_9companyname' as previousname_9companyname,
        record->>'previousname_10condate' as previousname_10condate,
        record->>'previousname_10companyname' as previousname_10companyname,
        record->>'confstmtnextduedate' as confstmtnextduedate,
        record->>'confstmtlastmadeupdate' as confstmtlastmadeupdate,
        _file,
        _loaded_at
    from {{ source('uk', 'companies') }}
    qualify _file = arg_max(_file, _loaded_at) over ()
)
select
    companynumber,  -- 8 characters: digits, or a prefix (SC Scotland, NI, OC LLP...) and digits
    companyname,
    regaddresscareof,
    regaddresspobox,
    regaddressaddressline1,
    regaddressaddressline2,
    regaddressposttown,
    regaddresscounty,
    regaddresscountry,
    regaddresspostcode,  -- e.g. AB1 0AA, as stg_onspd.pcds; free text, so not always a postcode
    companycategory,
    companystatus,
    countryoforigin,
    {{ dmy_date('dissolutiondate') }} as dissolutiondate,
    {{ dmy_date('incorporationdate') }} as incorporationdate,
    accountsaccountrefday::integer as accountsaccountrefday,
    accountsaccountrefmonth::integer as accountsaccountrefmonth,
    {{ dmy_date('accountsnextduedate') }} as accountsnextduedate,
    {{ dmy_date('accountslastmadeupdate') }} as accountslastmadeupdate,
    accountsaccountcategory,
    {{ dmy_date('returnsnextduedate') }} as returnsnextduedate,
    {{ dmy_date('returnslastmadeupdate') }} as returnslastmadeupdate,
    {{ dmy_date('confstmtnextduedate') }} as confstmtnextduedate,
    {{ dmy_date('confstmtlastmadeupdate') }} as confstmtlastmadeupdate,
    mortgagesnummortcharges::integer as mortgagesnummortcharges,
    mortgagesnummortoutstanding::integer as mortgagesnummortoutstanding,
    mortgagesnummortpartsatisfied::integer as mortgagesnummortpartsatisfied,
    mortgagesnummortsatisfied::integer as mortgagesnummortsatisfied,
    -- "<5-digit SIC 2007 code> - <description>"; "None Supplied" is null.
    nullif(siccodesictext_1, 'None Supplied') as siccodesictext_1,
    siccodesictext_2,
    siccodesictext_3,
    siccodesictext_4,
    limitedpartnershipsnumgenpartners::integer as limitedpartnershipsnumgenpartners,
    limitedpartnershipsnumlimpartners::integer as limitedpartnershipsnumlimpartners,
    uri,
    {{ dmy_date('previousname_1condate') }} as previousname_1condate,
    previousname_1companyname,
    {{ dmy_date('previousname_2condate') }} as previousname_2condate,
    previousname_2companyname,
    {{ dmy_date('previousname_3condate') }} as previousname_3condate,
    previousname_3companyname,
    {{ dmy_date('previousname_4condate') }} as previousname_4condate,
    previousname_4companyname,
    {{ dmy_date('previousname_5condate') }} as previousname_5condate,
    previousname_5companyname,
    {{ dmy_date('previousname_6condate') }} as previousname_6condate,
    previousname_6companyname,
    {{ dmy_date('previousname_7condate') }} as previousname_7condate,
    previousname_7companyname,
    {{ dmy_date('previousname_8condate') }} as previousname_8condate,
    previousname_8companyname,
    {{ dmy_date('previousname_9condate') }} as previousname_9condate,
    previousname_9companyname,
    {{ dmy_date('previousname_10condate') }} as previousname_10condate,
    previousname_10companyname,
    _file,
    _loaded_at
from raw
