-- ONS Postcode Directory, one row per UK postcode, live or terminated, with
-- the areas it falls in. Each quarterly release is a full snapshot that
-- replaces the last, so only the rows of the latest loaded file are kept.
with raw as (
    -- duckpipe keeps each CSV row in record, every value as text.
    select
        record->>'pcd7' as pcd7,
        record->>'pcd8' as pcd8,
        record->>'pcds' as pcds,
        record->>'dointr' as dointr,
        record->>'doterm' as doterm,
        record->>'usrtypind' as usrtypind,
        record->>'east1m' as east1m,
        record->>'north1m' as north1m,
        record->>'gridind' as gridind,
        record->>'lat' as lat,
        record->>'long' as long,
        record->>'ctry25cd' as ctry25cd,
        record->>'rgn25cd' as rgn25cd,
        record->>'cty25cd' as cty25cd,
        record->>'ced25cd' as ced25cd,
        record->>'lad25cd' as lad25cd,
        record->>'wd25cd' as wd25cd,
        record->>'parncp25cd' as parncp25cd,
        record->>'pcon24cd' as pcon24cd,
        record->>'eer20cd' as eer20cd,
        record->>'itl25cd' as itl25cd,
        record->>'ttwa15cd' as ttwa15cd,
        record->>'bua24cd' as bua24cd,
        record->>'npark16cd' as npark16cd,
        record->>'pfa23cd' as pfa23cd,
        record->>'educ23cd' as educ23cd,
        record->>'cal26cd' as cal26cd,
        record->>'lep21cd1' as lep21cd1,
        record->>'lep21cd2' as lep21cd2,
        record->>'hlth19cd' as hlth19cd,
        record->>'nhser24cd' as nhser24cd,
        record->>'icb26cd' as icb26cd,
        record->>'sicbl26cd' as sicbl26cd,
        record->>'pco19cd' as pco19cd,
        record->>'oa21cd' as oa21cd,
        record->>'lsoa21cd' as lsoa21cd,
        record->>'msoa21cd' as msoa21cd,
        record->>'ruc21ind' as ruc21ind,
        record->>'oa11cd' as oa11cd,
        record->>'lsoa11cd' as lsoa11cd,
        record->>'msoa11cd' as msoa11cd,
        record->>'wz11cd' as wz11cd,
        record->>'ruc11ind' as ruc11ind,
        record->>'oac11ind' as oac11ind,
        record->>'oa01cd' as oa01cd,
        record->>'lsoa01cd' as lsoa01cd,
        record->>'msoa01cd' as msoa01cd,
        record->>'ruc01ind' as ruc01ind,
        record->>'oac01ind' as oac01ind,
        record->>'wdstl05cd' as wdstl05cd,
        record->>'wdcas03cd' as wdcas03cd,
        record->>'ssr95cd' as ssr95cd,
        record->>'imd20ind' as imd20ind,
        _file,
        _loaded_at
    from {{ source('uk', 'onspd') }}
    qualify _file = arg_max(_file, _loaded_at) over ()
)
select
    pcds,  -- e.g. AB1 0AA, the format price paid uses
    pcd7,
    pcd8,
    strptime(dointr, '%Y%m')::date as dointr,
    strptime(doterm, '%Y%m')::date as doterm,  -- null while the postcode is live
    usrtypind = '1' as is_large_user,
    gridind,
    -- Postcodes without a grid reference (gridind 9) have 99.999999, 0.
    case when gridind <> '9' then east1m::integer end as east1m,
    case when gridind <> '9' then north1m::integer end as north1m,
    case when gridind <> '9' then lat::double end as lat,
    case when gridind <> '9' then long::double end as long,
    {{ area_code('ctry25cd') }} as ctry25cd,
    {{ area_code('rgn25cd') }} as rgn25cd,
    {{ area_code('cty25cd') }} as cty25cd,
    {{ area_code('ced25cd') }} as ced25cd,
    {{ area_code('lad25cd') }} as lad25cd,
    {{ area_code('wd25cd') }} as wd25cd,
    {{ area_code('parncp25cd') }} as parncp25cd,
    {{ area_code('pcon24cd') }} as pcon24cd,
    {{ area_code('eer20cd') }} as eer20cd,
    {{ area_code('itl25cd') }} as itl25cd,
    {{ area_code('ttwa15cd') }} as ttwa15cd,
    {{ area_code('bua24cd') }} as bua24cd,
    -- E65000001 and W31000001 are England's and Wales's "not in a national park".
    case when npark16cd not in ('E65000001', 'W31000001') then {{ area_code('npark16cd') }} end as npark16cd,
    {{ area_code('pfa23cd') }} as pfa23cd,
    {{ area_code('educ23cd') }} as educ23cd,
    {{ area_code('cal26cd') }} as cal26cd,
    {{ area_code('lep21cd1') }} as lep21cd1,
    {{ area_code('lep21cd2') }} as lep21cd2,
    {{ area_code('hlth19cd') }} as hlth19cd,
    {{ area_code('nhser24cd') }} as nhser24cd,
    {{ area_code('icb26cd') }} as icb26cd,
    {{ area_code('sicbl26cd') }} as sicbl26cd,
    {{ area_code('pco19cd') }} as pco19cd,
    {{ area_code('oa21cd') }} as oa21cd,
    {{ area_code('lsoa21cd') }} as lsoa21cd,  -- the LSOAs data.police.uk uses
    {{ area_code('msoa21cd') }} as msoa21cd,
    ruc21ind,
    {{ area_code('oa11cd') }} as oa11cd,
    {{ area_code('lsoa11cd') }} as lsoa11cd,
    {{ area_code('msoa11cd') }} as msoa11cd,
    {{ area_code('wz11cd') }} as wz11cd,
    ruc11ind,
    oac11ind,
    {{ area_code('oa01cd') }} as oa01cd,
    {{ area_code('lsoa01cd') }} as lsoa01cd,
    {{ area_code('msoa01cd') }} as msoa01cd,
    ruc01ind,
    oac01ind,
    {{ area_code('wdstl05cd') }} as wdstl05cd,
    {{ area_code('wdcas03cd') }} as wdcas03cd,
    ssr95cd,
    imd20ind::integer as imd20ind,
    _file,
    _loaded_at
from raw
